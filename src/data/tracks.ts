export function getTracksByNiche(niche: string) {
  return tracks.filter((t) => t.niche === niche);
}

export function getTopTracks(count = 10) {
  return [...tracks].sort((a, b) => b.monthlyStreams - a.monthlyStreams).slice(0, count);
}

export function getTotalStats() {
  return tracks.reduce(
    (acc, t) => ({
      totalStreams: acc.totalStreams + t.streams,
      totalRevenue: acc.totalRevenue + t.revenue,
      monthlyStreams: acc.monthlyStreams + t.monthlyStreams,
      monthlyRevenue: acc.monthlyRevenue + t.monthlyRevenue,
    }),
    { totalStreams: 0, totalRevenue: 0, monthlyStreams: 0, monthlyRevenue: 0 }
  );
}
